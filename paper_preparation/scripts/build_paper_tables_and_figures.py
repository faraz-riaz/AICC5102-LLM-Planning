    init["overestimates"] = init.initial_h > init.L_star
    table("A11_initial_state_accuracy", init, note="17 initial states per heuristic; estimates available in cost-aware worker logs, reused once per task. Interim R6 evidence, not sampled-state M3 completion.")
    for scope, subset in [("all90_four_methods", all90), ("easy30_five_methods", easy)]:
        common, _ = common_solved_table(subset)
