def escaped(value):
    text = str(value)
    mapping = {"\\": r"\textbackslash{}", "_": r"\_\allowbreak{}", "%": r"\%", "&": r"\&",
               "#": r"\#", "$": r"\$", "{": r"\{", "}": r"\}",
               "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(mapping.get(c, c) for c in text)


def cell(value):
    if pd.isna(value):
        return "--"
    if isinstance(value, (float, np.floating)):
        return f"{value:.3g}"
    return str(value)


def table(name, frame, placement="appendix", note=""):
    """CSV stays full precision; previews round. Wide tables become vertical panels."""
    folder = OUT / "tables" / placement
    folder.mkdir(parents=True, exist_ok=True)
    frame.to_csv(folder / f"{name}.csv", index=False, lineterminator="\n")
    pretty = frame.map(cell)
    (folder / f"{name}.md").write_text(f"# {name}\n\n{note}\n\n" + to_markdown(pretty) + "\n", encoding="utf-8")
    # Each panel repeats identifying columns; normal template font, no scaling.
    identifier_count = min(2, len(frame.columns))
    while identifier_count < min(4, len(frame.columns)) and frame.iloc[:, :identifier_count].duplicated().any():
        identifier_count += 1
    ids = list(frame.columns[:identifier_count])
    rest = list(frame.columns[len(ids):])
    panel_capacity = 6-len(ids)
    panels = [ids + rest[i:i+panel_capacity] for i in range(0, len(rest), panel_capacity)] or [ids]
    tex = ["% Generated by paper_preparation/scripts/build_paper_tables_and_figures.py",
           "% Requires array,longtable; place outside table floats. Normal font size.",
           "% CSV is authoritative. Split panels repeat identifying columns."]
    for i, cols in enumerate(panels):
        n = len(cols)
        spec = "".join([r">{\raggedright\arraybackslash}p{\dimexpr " +
                        f"{1/n:.6f}" + r"\linewidth-2\tabcolsep\relax}"] * n)
        tex += [r"\begingroup", r"\setlength{\tabcolsep}{2pt}",
                r"\begin{longtable}{" + spec + "}", r"\hline",
                " & ".join(escaped(c.replace("_", " ")) for c in cols) + r" \\ \hline\endhead"]
        for row in pretty[cols].itertuples(index=False, name=None):
            tex.append(" & ".join(escaped(v) for v in row) + r" \\")
        tex += [r"\hline", r"\end{longtable}", r"\endgroup"]
    tex += ["% " + note.replace("\n", " ")]
    (folder / f"{name}.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")


def save(fig, name, placement):
    folder = OUT / "figures" / placement
    folder.mkdir(parents=True, exist_ok=True)
    for suffix in ["pdf", "png"]:
        metadata = {"Creator": "paper_preparation/scripts/build_paper_tables_and_figures.py"}
        if suffix == "pdf":
            metadata.update({"CreationDate": None, "ModDate": None})
        fig.savefig(folder / f"{name}.{suffix}", bbox_inches="tight", pad_inches=.03,
                    metadata=metadata)
    plt.close(fig)


def verify_raw(runs, baseline):
    """No grounding: compare converted records, sidecars, schema and saved plan hashes."""
    rebuilt = pd.read_csv(io.StringIO(pd.DataFrame(convert(RAW, ["w8-m2-", "w8-gbfs-"])).to_csv(index=False)))
    pd.testing.assert_frame_equal(runs.sort_index(axis=1), rebuilt.sort_index(axis=1),
                                  check_dtype=False, check_exact=False, rtol=1e-10, atol=1e-10)
    batches = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((RAW / "batches").glob("*.json"))
               if p.name.startswith(("w8-m2-", "w8-gbfs-"))]
    seeds, ids = {}, []
    for b in batches:
        assert b["hash_seed_scope"] == "task"
        assert b["command"][b["command"].index("--workers")+1] == "8"
        ids.extend(b["run_ids"])
        seeds.update(b["python_hash_seeds"])
    assert len(ids) == len(set(ids)) == 870
    raw = {}
    for run_id in ids:
        r = json.loads((RAW / f"{run_id}.json").read_text(encoding="utf-8"))
        assert not validate_record(r), run_id
        assert r["time_limit_s"] == 60 and r["memory_limit_mib"] == 4096
        assert r["benchmark_version"] == "aicc5102-90-v1"
        assert r["timeout_enforced"] and r["memory_limit_enforced"]
        assert (RAW / "logs" / f"{run_id}.log").is_file()
        if r["status"] == "success":
            assert r["plan_valid"] is True and r["plan_cost"] == r["plan_length"]
            actions = [s.strip() for s in (RAW / "plans" / f"{run_id}.soln").read_text().splitlines() if s.strip()]
            assert len(actions) == r["plan_length"]
        raw[run_id] = r
    for r in baseline.itertuples():
        s = raw[r.run_id]
        assert r.status == s["status"] and r.solved == s["solved"]
        for k in ["plan_length", "nodes_expanded", "wall_time_s", "peak_memory_mib"]:
            a, b = getattr(r, k), s[k]
            assert (pd.isna(a) and b is None) or np.isclose(a, b)
    seed_rows = pd.DataFrame([{"domain": r["domain"], "problem_id": r["problem_id"],
                               "hash_seed": seeds[i]} for i, r in raw.items()])
    assert seed_rows.groupby(["domain", "problem_id"]).hash_seed.nunique().eq(1).all()
    manifest = pd.read_csv(ROOT / "benchmarks/manifest.csv")
    tasks = set(zip(manifest.domain, manifest.problem_id))
    assert set(zip(runs.domain, runs.problem_id)) == tasks
    assert not runs.duplicated(["domain", "problem_id", "heuristic_id", "algorithm_label"]).any()
    for method in METHODS:
        for h in COLORS:
            sub = runs[(runs.algorithm_label == method) & (runs.heuristic_id == h)]
            expected = set(zip(manifest[manifest.difficulty == "easy"].domain,
                               manifest[manifest.difficulty == "easy"].problem_id)) if method == "ida_star" else tasks
            assert set(zip(sub.domain, sub.problem_id)) == expected
    return {"raw_records_checked": len(raw), "m2_reconverted_rows": len(rebuilt),
            "m1_summary_rows_checked": len(baseline), "logs_present": len(raw),
            "successful_saved_plans_checked": sum(r["solved"] for r in raw.values()),
            "task_seed_consistent": True,
            "plan_check_scope": "saved length/hash and recorded validation; no new grounding or replay"}


